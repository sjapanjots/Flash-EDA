"""
flasheda.contract.script
~~~~~~~~~~~~~~~~~~~~~~~~
Exports a contract as code:

  render_check_script  standalone DuckDB script (no flasheda needed): one
                       pass over the file, prints every check, exits 1 on
                       failure, so it can gate a pipeline or CI job
  render_pandera       a pandera DataFrameSchema with the same rules
"""

from __future__ import annotations

from typing import List, Optional, Tuple

from .rules import ColumnRule, Contract


def _ident(name: str) -> str:
    return '"' + str(name).replace('"', '""') + '"'


def _lit(value: str) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def _invalid(c: str, kind: str) -> str:
    txt = f"CAST({c} AS VARCHAR)"
    if kind in ("number", "integer"):
        return f"(count({c}) - count(TRY_CAST(trim({txt}) AS DOUBLE)))"
    if kind == "datetime":
        return f"(count({c}) - count(TRY_CAST({txt} AS TIMESTAMP)))"
    if kind == "bool":
        return f"(count({c}) FILTER (WHERE lower(trim({txt})) NOT IN ('true', 'false', '1', '0')))"
    return "0"


def compile_checks(contract: Contract) -> List[Tuple[str, str, str, str, float]]:
    """
    (column, rule, SQL expression, operator, limit) for every column rule.
    Percentages are rounded to 2 decimals, as in flasheda.check.
    """
    out = []
    for r in contract.columns:
        c = _ident(r.name)
        non_null = f"NULLIF(count({c}), 0)"
        if r.kind == "text":
            out.append((r.name, "null %",
                        f"round((count(*) - count({c})) * 100.0 / count(*), 2)", "<=", r.max_null_pct))
        else:
            inv = _invalid(c, r.kind)
            out.append((r.name, "null or unparseable %",
                        f"round((count(*) - count({c}) + {inv}) * 100.0 / count(*), 2)", "<=",
                        round(r.max_null_pct + r.max_invalid_pct, 2)))
            out.append((r.name, f"values parse as {r.kind} (% invalid)",
                        f"coalesce(round({inv} * 100.0 / {non_null}, 2), 0)", "<=", r.max_invalid_pct))
        if r.min is not None:
            out.append((r.name, "minimum", f"min(TRY_CAST({c} AS DOUBLE))", ">=", r.min))
        if r.max is not None:
            out.append((r.name, "maximum", f"max(TRY_CAST({c} AS DOUBLE))", "<=", r.max))
        if r.allowed is not None:
            values = ", ".join(_lit(v) for v in r.allowed)
            out.append((r.name, "unexpected values %",
                        f"coalesce(round(count({c}) FILTER (WHERE CAST({c} AS VARCHAR) NOT IN ({values}))"
                        f" * 100.0 / {non_null}, 2), 0)", "<=", r.max_unexpected_pct))
        if r.unique:
            out.append((r.name, "duplicate values", f"count({c}) - count(DISTINCT {c})", "<=", 0))
    return out


def render_check_script(contract: Contract, source: Optional[str] = None) -> str:
    checks = compile_checks(contract)
    lines = ",\n".join(f"    ({col!r}, {rule!r}, {expr!r}, {op!r}, {limit!r})"
                       for col, rule, expr, op, limit in checks)
    columns = [r.name for r in contract.columns]
    return f'''"""
Data contract check generated by FlashEDA

Checks every row of SOURCE in one DuckDB pass (works on files larger than
memory), prints each check and exits with status 1 if any fail, so it can
gate a pipeline or CI job.

    python {{this file}} [path/to/data.csv|.parquet]

Requires: duckdb
"""

import sys

import duckdb

SOURCE = {source!r}
COLUMNS = {columns!r}
ALLOW_EXTRA_COLUMNS = {contract.allow_extra_columns!r}

# (column, rule, SQL expression, operator, limit)
CHECKS = [
{lines}
]


def scan(path: str) -> str:
    quoted = path.replace("'", "''")
    if path.lower().endswith((".parquet", ".pq")):
        return f"read_parquet('{{quoted}}')"
    delim = "\\\\t" if path.lower().endswith((".tsv", ".txt")) else ","
    return (f"read_csv('{{quoted}}', delim = '{{delim}}', header = true, "
            "auto_type_candidates = ['BIGINT', 'DOUBLE', 'VARCHAR'])")


def main(path: str) -> int:
    con = duckdb.connect()
    table = scan(path)
    present = [row[0] for row in con.execute(f"DESCRIBE SELECT * FROM {{table}}").fetchall()]
    results = []

    missing = [c for c in COLUMNS if c not in present]
    results.append((None, "required columns", not missing, missing or "all present", f"{{len(COLUMNS)}} columns"))
    extra = [c for c in present if c not in COLUMNS]
    if extra and not ALLOW_EXTRA_COLUMNS:
        results.append((None, "no extra columns", False, extra, "none"))

    runnable = [c for c in CHECKS if c[0] in present]
    rows, *values = con.execute(
        "SELECT count(*), " + ", ".join(c[2] for c in runnable) + f" FROM {{table}}"
    ).fetchone() if runnable else (con.execute(f"SELECT count(*) FROM {{table}}").fetchone()[0],)
    for (col, rule, _, op, limit), value in zip(runnable, values):
        if value is None:
            continue
        passed = value <= limit if op == "<=" else value >= limit
        results.append((col, rule, passed, value, f"{{op}} {{limit}}"))

    failed = [r for r in results if not r[2]]
    for col, rule, passed, observed, expected in results:
        where = f"{{col}}: " if col else ""
        print(f"[{{'PASS' if passed else 'FAIL'}}] {{where}}{{rule}}: observed {{observed}}, expected {{expected}}")
    print(f"\\n{{len(results) - len(failed)}}/{{len(results)}} checks passed on {{rows:,}} rows")
    return 1 if failed else 0


if __name__ == "__main__":
    path = sys.argv[1] if len(sys.argv) > 1 else SOURCE
    if path is None:
        sys.exit("usage: python check.py path/to/data.csv")
    sys.exit(main(path))
'''


def render_pandera(contract: Contract) -> str:
    """
    A pandera schema expressing the same rules (tolerances become custom
    checks). Null checks use ignore_na=False: pandera drops nulls before
    running a check otherwise.
    """
    cols = []
    for r in contract.columns:
        cols.append(f"        {r.name!r}: pa.Column(\n"
                    f"            nullable=True,\n"
                    f"            unique={r.unique!r},\n"
                    f"            required=True,\n"
                    f"            checks=[\n{_pandera_checks(r)}            ],\n"
                    f"        ),")
    body = "\n".join(cols)
    return f'''"""
pandera schema generated by FlashEDA from a data contract.

    schema.validate(df, lazy=True)   # raises SchemaErrors listing every failure

Requires: pandera, pandas
"""

import pandas as pd
import pandera.pandas as pa


def _pct(mask) -> float:
    return round(float(mask.mean()) * 100, 2) if len(mask) else 0.0


def _parses(s: pd.Series, kind: str) -> pd.Series:
    s = s.dropna()
    if kind in ("number", "integer"):
        return s.map(lambda v: isinstance(v, (int, float)) and not isinstance(v, bool)) | \\
            pd.to_numeric(s.astype(str).str.strip(), errors="coerce").notna()
    if kind == "datetime":
        return pd.to_datetime(s.astype(str), errors="coerce", format="mixed").notna()
    if kind == "bool":
        return s.astype(str).str.strip().str.lower().isin(["true", "false", "1", "0"])
    return pd.Series(True, index=s.index)


schema = pa.DataFrameSchema(
    {{
{body}
    }},
    strict={not contract.allow_extra_columns!r},
)
'''


def _pandera_checks(r: ColumnRule) -> str:
    checks = []
    if r.kind == "text":
        checks.append(f"pa.Check(lambda s: _pct(s.isna()) <= {r.max_null_pct!r}, ignore_na=False, "
                      f"error='null % above {r.max_null_pct}')")
    else:
        limit = round(r.max_null_pct + r.max_invalid_pct, 2)
        checks.append(f"pa.Check(lambda s: _pct(s.isna() | ~_parses(s, {r.kind!r}).reindex(s.index, fill_value=True)) "
                      f"<= {limit!r}, ignore_na=False, error='null or unparseable % above {limit}')")
        checks.append(f"pa.Check(lambda s: _pct(~_parses(s, {r.kind!r})) <= {r.max_invalid_pct!r}, "
                      f"error='unparseable % above {r.max_invalid_pct}')")
    if r.min is not None or r.max is not None:
        x = "pd.to_numeric(s, errors='coerce')"
        if r.min is not None:
            checks.append(f"pa.Check(lambda s: not ({x} < {r.min!r}).any(), error='below {r.min}')")
        if r.max is not None:
            checks.append(f"pa.Check(lambda s: not ({x} > {r.max!r}).any(), error='above {r.max}')")
    if r.allowed is not None:
        checks.append(f"pa.Check(lambda s: _pct(~s.dropna().astype(str).isin({list(r.allowed)!r})) "
                      f"<= {r.max_unexpected_pct!r}, error='unexpected values above {r.max_unexpected_pct}%')")
    return "".join(f"                {c},\n" for c in checks)
