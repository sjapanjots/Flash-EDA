"""
flasheda.modeling.script
~~~~~~~~~~~~~~~~~~~~~~~~
Renders a standalone training script for the chosen model. It reads the
output of the prep script (cleaning + features), cross-validates with the
same split and metric used to pick the model, fits on all rows and saves
the model with joblib.
"""

from __future__ import annotations

from typing import List, Optional

from .specs import ModelSpec


def render_training_script(
    spec: ModelSpec,
    *,
    task: str,
    target: str,
    features: List[str],
    scoring: str,
    metric_label: str,
    positive: Optional[str],
    time_order: List[str],
    data: str,
    model_path: str,
    n_splits: int,
    summary: str,
) -> str:
    if time_order:
        cv = "TimeSeriesSplit(n_splits=N_SPLITS)"
        cv_import = "TimeSeriesSplit"
        split_note = f"time-ordered by {', '.join(time_order)}: train on the past, test on the future"
    elif task == "regression":
        cv = "KFold(n_splits=N_SPLITS, shuffle=True, random_state=RANDOM_STATE)"
        cv_import = "KFold"
        split_note = "shuffled K-fold"
    else:
        cv = "StratifiedKFold(n_splits=N_SPLITS, shuffle=True, random_state=RANDOM_STATE)"
        cv_import = "StratifiedKFold"
        split_note = "stratified K-fold (keeps the class balance in every fold)"

    if task == "binary":
        target_line = "y = (df[TARGET].astype(str) == POSITIVE).astype(int)"
        task_text = f"binary classification of {target!r} (positive class: {positive!r})"
    elif task == "multiclass":
        target_line = "y = df[TARGET].astype(str)"
        task_text = f"multiclass classification of {target!r}"
    else:
        target_line = "y = df[TARGET].astype(float)"
        task_text = f"regression of {target!r}"

    imports = [
        "import joblib",
        "import pandas as pd",
        f"from {spec.module} import {spec.cls}",
        f"from sklearn.model_selection import {cv_import}, cross_validate",
    ]
    layers = []
    if spec.impute:
        imports.append("from sklearn.impute import SimpleImputer")
        layers.append('SimpleImputer(strategy="median", keep_empty_features=True)')
    if spec.scale:
        imports.append("from sklearn.preprocessing import StandardScaler")
        layers.append("StandardScaler()")
    params = ", ".join(f"{k}={v!r}" for k, v in spec.params.items())
    layers.append(f"{spec.cls}({params})")
    if len(layers) > 1:
        imports.append("from sklearn.pipeline import make_pipeline")
        build = "make_pipeline(\n        " + ",\n        ".join(layers) + ",\n    )"
    else:
        build = layers[0]

    feature_lines = "\n".join(f"    {f!r}," for f in features)
    sort_line = (
        '    df = df.sort_values(TIME_ORDER, na_position="first", kind="stable")\n'
        if time_order else ""
    )
    return f'''"""
Training script generated by FlashEDA

Task:   {task_text}
Model:  {spec.name}: {summary}
Metric: {metric_label} ({scoring}), {split_note}
Data:   {data}, the output of the prep script (cleaning + features)

Requires: scikit-learn, pandas, pyarrow
scikit-learn trains in memory: above MAX_ROWS rows a random subset is used.
"""

{chr(10).join(imports)}

DATA = {data!r}
MODEL_PATH = {model_path!r}
TARGET = {target!r}
POSITIVE = {positive!r}
TIME_ORDER = {time_order!r}
SCORING = {scoring!r}
N_SPLITS = {n_splits}
MAX_ROWS = 2_000_000
RANDOM_STATE = 42
FEATURES = [
{feature_lines}
]


def load():
    df = pd.read_parquet(DATA, columns=FEATURES + [TARGET] + [c for c in TIME_ORDER if c not in FEATURES])
    df = df[df[TARGET].notna()]
    if len(df) > MAX_ROWS:
        df = df.sample(MAX_ROWS, random_state=RANDOM_STATE)
{sort_line}    X = df[FEATURES]
    {target_line}
    return X, y


def build_model():
    return {build}


def main() -> None:
    X, y = load()
    cv = {cv}
    scores = cross_validate(build_model(), X, y, scoring=SCORING, cv=cv)["test_score"]
    sign = -1 if SCORING.startswith("neg_") else 1
    print(f"{metric_label}: {{sign * scores.mean():.4f}} ± {{scores.std():.4f}} "
          f"({{N_SPLITS}}-fold CV on {{len(X):,}} rows)")

    model = build_model().fit(X, y)
    joblib.dump(model, MODEL_PATH)
    print(f"Saved model -> {{MODEL_PATH}}")


if __name__ == "__main__":
    main()
'''
