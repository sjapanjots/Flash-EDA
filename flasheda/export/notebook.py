"""
flasheda.export.notebook
~~~~~~~~~~~~~~~~~~~~~~~~
Everything FlashEDA found and generated, as one runnable Jupyter notebook:

    report = flasheda.analyze("orders.csv", target="churn")
    report.to_notebook("orders.ipynb", train=True, time="created_at")

Sections: summary and warnings, the analysis (re-runnable), the cleaning
plan with its code, and optionally model training, a time-series forecast
and a data-contract check. Each code section is a generated script that
was validated on the sample, so the notebook runs top to bottom.

Written as plain nbformat-4 JSON, no extra dependency.
"""

from __future__ import annotations

import dataclasses
import json
import uuid
from pathlib import Path
from typing import TYPE_CHECKING, Any, Dict, List, Optional, Union

if TYPE_CHECKING:
    from ..report import EDAReport


def to_notebook(
    report: "EDAReport",
    path: Union[str, Path] = "flasheda_analysis.ipynb",
    *,
    source: Optional[str] = None,
    engine: Optional[str] = None,
    output: str = "cleaned.parquet",
    features: bool = False,
    train: bool = False,
    time: Optional[str] = None,
    value: Optional[str] = None,
    contract: bool = True,
) -> Path:
    """
    Write a notebook for `report`.

    source   : data path used in the notebook (default: the analysed file)
    train    : add model training (needs a target; implies features)
    time     : add a time-series profile and forecast on this column
    contract : add a data-contract check of the source
    """
    from .. import __version__

    source = source or report.source
    if source is None:
        raise ValueError("The report wasn't built from a file; pass source='path/to/data.parquet'.")
    if report.source != str(source):
        # generated code must read the notebook's source (its file type decides the reader)
        report = dataclasses.replace(report, source=str(source))
    target = (report.target or {}).get("target")
    if train and not target:
        raise ValueError("train=True needs a target: flasheda.analyze(source, target='column').")

    cells: List[Dict[str, Any]] = []
    md = lambda text: cells.append(_cell("markdown", text))   # noqa: E731
    code = lambda text: cells.append(_cell("code", text))     # noqa: E731

    rows, cols = report.original_shape
    md(f"# FlashEDA analysis: `{Path(source).name}`\n\n"
       f"{rows:,} rows × {cols} columns, analysed on a {report.sample_size:,}-row sample"
       + (f", target `{target}` ({report.target['task']})" if target else "")
       + f".\n\nGenerated by FlashEDA {__version__}. Every code cell below was generated "
       "and validated on the sample.")
    if report.warnings:
        md("## Warnings\n\n" + "\n".join(f"- {w}" for w in report.warnings))

    md("## Analysis\nRe-run the analysis (a fixed-size sample, so it takes seconds at any size).")
    code("import flasheda as fe\n\n"
         f"SOURCE = {source!r}\n"
         f"report = fe.analyze(SOURCE{f', target={target!r}' if target else ''}, save_pdf=False)\n"
         "report.show()")

    if train:
        result = report.train(engine, output=output)
        prep, steps = result.prep, result.prep.plan.describe()
    else:
        prep = report.codegen(engine, output=output, features=features)
        steps = prep.plan.describe()
    md(f"## Cleaning{' and features' if train or features else ''} ({prep.engine})\n\n"
       + ("\n".join(f"1. {s}" for s in steps) if steps else "No cleaning needed.")
       + f"\n\nThe next cell reads the full data and writes `{output}`.")
    code(_as_cell(prep.code, source))

    if train:
        md(f"## Model\n\nCompared on the sample ({result.metric}, "
           f"{'lower' if result.lower_is_better else 'higher'} is better):\n\n"
           + _markdown_table(result.leaderboard)
           + f"\n\nThe next cell cross-validates **{result.best}** on `{output}` and saves the model.")
        code(_as_cell(result.train_code, None))

    if time:
        from ..timeseries import timeseries
        ts = timeseries(source, time=time, value=value)
        fc = ts.forecast()
        md(f"## Time series: {ts.metric} per {ts.freq}\n\n"
           f"Trend **{ts.trend['direction']}** ({ts.trend['change_per_year_pct']:+.1f}% per year); "
           f"season length {ts.season_length or 'none'}; best forecast baseline **{fc.method}**.")
        code("ts = fe.timeseries(SOURCE, " + f"time={time!r}" + (f", value={value!r}" if value else "")
             + ")\nts.show()\nfc = ts.forecast()\nfc.show()\nfc.forecast")

    if contract:
        md("## Data contract\nRules learned from the sample. Run the check on any new file "
           "with the same columns; it reports every rule that fails.")
        code("contract = report.contract()\ncontract.save('contract.json')\n"
             "result = fe.check(SOURCE, contract)\nresult.show()\nassert result.ok, result.failures")

    nb = {
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "cells": cells,
    }
    path = Path(path)
    path.write_text(json.dumps(nb, indent=1, ensure_ascii=False), encoding="utf-8")
    return path


def _as_cell(script: str, source: Optional[str]) -> str:
    """A generated script as a notebook cell: drop the module docstring and
    run main() directly (Jupyter's __name__ is already "__main__")."""
    body = script
    if body.startswith('"""'):
        end = body.index('"""', 3) + 3
        body = body[end:].lstrip("\n")
    if source is not None and "\nSOURCE = " in body:
        body = body.replace("\nSOURCE = ", "\nSOURCE = SOURCE  # same file: ", 1)
    return body.rstrip("\n")


def _markdown_table(df) -> str:
    cols = list(df.columns)
    fmt = lambda v: f"{v:.4f}" if isinstance(v, float) else str(v)   # noqa: E731
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def _cell(kind: str, text: str) -> Dict[str, Any]:
    cell: Dict[str, Any] = {"cell_type": kind, "id": uuid.uuid4().hex[:8], "metadata": {},
                            "source": text.splitlines(keepends=True)}
    if kind == "code":
        cell.update(execution_count=None, outputs=[])
    return cell
