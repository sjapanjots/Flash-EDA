"""
flasheda.codegen.writers.base
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
Shared script layout for every engine writer.

Each generated script has the same shape:
  SOURCE / OUTPUT constants
  transform(...)  — the cleaning steps, one commented block per step
  main()          — load full data → transform → write Parquet
"""

from __future__ import annotations

import textwrap
from abc import ABC, abstractmethod
from pathlib import Path
from typing import Any, List, Optional

from ..steps import Plan, Step


class Writer(ABC):
    engine: str = ""
    install_hint: str = ""
    columns: Optional[List[str]] = None
    sql: Any = None
    reads_sql = False           # writers that can load from a database URL

    def render(
        self,
        plan: Plan,
        source: Optional[str],
        output: str,
        columns: Optional[List[str]] = None,
        sql: Any = None,
    ) -> str:
        """`columns` are the source's column names, when known; `sql` a database source."""
        self.columns = list(columns) if columns is not None else None
        self.sql = sql
        if sql is not None and not self.reads_sql:
            raise ValueError(
                f"The {self.engine} writer can't read from a database directly. Use engine='pandas', "
                "or export first: flasheda.sql(...).to_parquet('data.parquet'), then analyze that file.")
        if sql is not None:
            source = sql.display
        parts = [
            self._docstring(plan, source),
            self.imports(),
            f"SOURCE = {source!r}\nOUTPUT = {output!r}",
            self.transform(plan),
            self.main(source),
            'if __name__ == "__main__":\n    main()',
        ]
        return "\n\n\n".join(p.strip("\n") for p in parts if p) + "\n"

    def _docstring(self, plan: Plan, source: Optional[str]) -> str:
        lines = [
            f"Cleaning pipeline generated by FlashEDA — engine: {self.engine}",
            f"Source: {source or '<in-memory DataFrame>'}",
            "",
            "Fill values and clip bounds were learned from a random sample.",
        ]
        if self.install_hint:
            lines.append(f"Requires: {self.install_hint}")
        lines += ["", "Steps:"] + [f"  {i}. {d}" for i, d in enumerate(plan.describe(), 1)]
        if not plan.steps:
            lines.append("  (none — the data looked clean)")
        return '"""\n' + "\n".join(lines) + '\n"""'

    @staticmethod
    def comment(step: Step) -> str:
        return f"# {step.reason}" if step.reason else ""

    @staticmethod
    def indent(lines: List[str], level: int = 1) -> str:
        return textwrap.indent("\n".join(lines), "    " * level)

    @abstractmethod
    def imports(self) -> str: ...

    @abstractmethod
    def transform(self, plan: Plan) -> str: ...

    @abstractmethod
    def main(self, source: Optional[str]) -> str: ...


def source_format(source: Optional[str]) -> str:
    if source is None:
        return "parquet"
    ext = Path(source).suffix.lower()
    if ext in (".parquet", ".pq"):
        return "parquet"
    if ext in (".tsv", ".txt"):
        return "tsv"
    return "csv"
